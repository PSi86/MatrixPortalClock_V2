/* ----------------------------------------------------------------------
   The pictures of the item icons (ItemIcon in band_data.h): 24x24 pixels in
   up to three parts. Each part has a role - a cloud, the sun, rain, the
   warning triangle - and whoever draws the icon gives every role its colour,
   so a cloud is white, rain blue and the triangle the colour of its warning's
   level. A banner on the 64x32 clock shows an alert's icon on its own.

   Each icon is drawn here as it looks: '.' leaves a pixel dark, '#', '+' and
   '*' light it as the icon's first, second and third part. iconRow() packs a
   row into two bit planes while compiling, so the firmware holds about 200
   bytes an icon and none of the text. They are part of the firmware, not of the
   GIF pack: the band and the banners work without any data loaded onto the
   clock.

   Drizzle, rain and snow come in three pictures: one, two or three of their
   drops or flakes say how heavy it is (light, moderate, heavy), and their
   colour how likely (decided on 2026-10-11).
   ---------------------------------------------------------------------- */
#pragma once

#include <Arduino.h>
#include "band_data.h"

const uint8_t ICON_SIZE = 24;

// What a part of an icon is, for its colour.
enum IconRole : uint8_t {
  ROLE_NONE, ROLE_CLOUD, ROLE_CLOUD_WET, ROLE_SUN, ROLE_RAYS, ROLE_MOON, ROLE_FOG, ROLE_RAIN, ROLE_SNOW,
  ROLE_BOLT, ROLE_LEVEL, ROLE_MARK, ROLE_WIND, ROLE_GLASS, ROLE_COLD, ROLE_HOT, ROLE_WAVES, ROLE_FLAKE,
};

// One row of an icon: the part of each pixel, 0 for dark, as two bit planes
// with the leftmost pixel in bit 23.
struct IconRow { uint32_t lo, hi; };

constexpr IconRow iconRow(const char (&row)[ICON_SIZE + 1]) {
  uint32_t lo = 0, hi = 0;
  for (uint8_t i = 0; i < ICON_SIZE; i++) {
    uint8_t part = row[i] == '#' ? 1 : row[i] == '+' ? 2 : row[i] == '*' ? 3 : 0;
    lo = (lo << 1) | (part & 1u);
    hi = (hi << 1) | (part >> 1);
  }
  return { lo, hi };
}

// The roles of parts '#', '+' and '*', and the rows.
