/* ----------------------------------------------------------------------
   The pictures of the info band's item icons (ItemIcon in band_data.h):
   24x24 pixels in one colour, which whoever draws them picks. A banner on
   the 64x32 clock shows an alert's icon on its own, in the alert colour.

   Each icon is drawn here as it looks: '#' lights a pixel, '.' leaves it
   dark. iconRow() packs a row into the bits of a number while compiling,
   so the firmware holds 96 bytes an icon and none of the text. They are
   part of the firmware, not of the GIF pack: the band and the banners work
   without any data loaded onto the clock.
   ---------------------------------------------------------------------- */
#pragma once

#include <Arduino.h>
#include "band_data.h"

const uint8_t ICON_SIZE = 24;

// One row of an icon: its leftmost pixel in bit 23.
constexpr uint32_t iconRow(const char (&row)[ICON_SIZE + 1]) {
  uint32_t bits = 0;
  for (uint8_t i = 0; i < ICON_SIZE; i++) { bits = (bits << 1) | (row[i] == '#' ? 1u : 0u); }
  return bits;
}

