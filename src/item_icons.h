// The picture of an icon at an intensity (BandItem::intensity): drizzle, rain
// and snow by how heavy they are, every other icon as it is.
inline const IconBits &iconPicture(uint8_t icon, uint8_t intensity) {
  if (icon >= ICON_COUNT) { icon = ICON_NONE; }
  bool light = intensity == INTENSITY_LIGHT, heavy = intensity == INTENSITY_HEAVY;
  if (icon == ICON_DRIZZLE && light) { return ICON_PICTURES[PIC_DRIZZLE_LIGHT]; }
  if (icon == ICON_DRIZZLE && heavy) { return ICON_PICTURES[PIC_DRIZZLE_HEAVY]; }
  if (icon == ICON_RAIN && light)    { return ICON_PICTURES[PIC_RAIN_LIGHT]; }
  if (icon == ICON_RAIN && heavy)    { return ICON_PICTURES[PIC_RAIN_HEAVY]; }
  if (icon == ICON_SNOW && light)    { return ICON_PICTURES[PIC_SNOW_LIGHT]; }
  if (icon == ICON_SNOW && heavy)    { return ICON_PICTURES[PIC_SNOW_HEAVY]; }
  return ICON_PICTURES[icon];
}
