/* ----------------------------------------------------------------------
   Wall clock hardware spike - not part of the clock firmware.

   For the Waveshare ESP32-S3-RGB-Matrix with 64x64 P3 panels at 1/32 scan
   (UI concept, section "Wall clock hardware"). It answers what the clock
   firmware needs to know before it supports the board, with the panel driver
   the clock runs on the MatrixPortal S3 (ESP32-HUB75-MatrixPanel-DMA):
     - which driver chip init, clock phase and bus clock the panels need,
     - how the chain is cabled (which panel sits where, turned how),
     - refresh rate, colour depth and frame buffer memory per layout
       (2x1 = 128x64, 3x2 = 192x128, 4x2 = 256x128),
     - how long a full frame takes to draw through the panel mapping,
     - whether WiFi works beside the running panel bus,
     - which I2C devices answer on the board bus and on the GPIO header.

   Builds: env:wallclock_spike (frame buffer in internal RAM) and
   env:wallclock_spike_psram (frame buffer in PSRAM, -D SPIRAM_DMA_BUFFER).

   Carried over from the clock on the MatrixPortal S3:
     - the HUB75 pins run at GPIO drive strength 0: at the driver's 3 the
       nonstop bus kept WiFi from working (20 of 30 TCP connects failed);
     - clock phase 0 is the default (the MatrixPortal panel needs it, with 1
       the picture sits one column to the left);
     - NO_CIE1931: brightness and colours stay linear, as in the clock;
     - GIFs: decoded as in the clock, gamma 2.2, drawn centred and unscaled.

   Panel: the BOOT button steps through the screens (short press) and the
   brightness (held). Screens:
     1 Chain   each panel of the chain as the driver sees it: its number in
               the chain, an arrow to its own top, its left column red and its
               right column green. Shows the cabling, how each panel is turned
               and the clock phase (a missing red or a doubled green column).
     2 Layout  the whole wall through the panel mapping: frame, diagonal,
               circle, an arrow up. Continuous and upright when the mapping
               fits the cabling.
     3 Ramps   red, green, blue and white from 0 to 255, and white 0..32.
     4 Motion  stripes moving across the whole wall, every pixel drawn each
               frame: tearing, smoothness, and the time a full frame takes.
     5 GIFs    the built-in GIFs that fit, one after the other.
     6 Info    the settings and measurements.

   USB console (115200): "help" lists the commands. Settings live in NVS
   (namespace "wcspike") and the driver's take effect after a restart, which
   the command does itself. Three starts in a row that do not get past the
   panel start bring the defaults back.
   ------------------------------------------------------------------------- */
