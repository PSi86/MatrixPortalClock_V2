// Applies a driver setting: saved, then a restart.
void setAndRestart(uint8_t &field, long value, long lo, long hi) {
  if (value < lo || value > hi) { Serial.printf("Out of range (%ld..%ld)\n", lo, hi); return; }
  field = (uint8_t)value;
  settingsSave();
  restartBlank();
}

// Applies a change of the panel placement at once.
void placementChanged() {
  buildCells();
  if (screen == SCR_GIF) { gifStop(); }      // the next GIF that fits the wall as it is now
  settingsSave();
  printStatus();
  drawScreen(true);
}

void runCommand(char *line) {
  char *cmd = strtok(line, " \t");
  if (!cmd) { return; }
  char *a1 = strtok(nullptr, " \t"), *a2 = strtok(nullptr, " \t"), *a3 = strtok(nullptr, " \t"),
       *a4 = strtok(nullptr, " \t");
  long v = a1 ? strtol(a1, nullptr, 10) : -1;

  if (!strcmp(cmd, "help")) { printHelp(); }
  else if (!strcmp(cmd, "show")) { printStatus(); }
  else if (!strcmp(cmd, "layout") && a1) {
    int cols = 0, rows = 0;
    if (sscanf(a1, "%dx%d", &cols, &rows) != 2 || cols < 1 || rows < 1 || cols > MAX_SIDE || rows > MAX_SIDE ||
        cols * rows > MAX_PANELS) {
      Serial.println("Layout: <cols>x<rows>, at most 4 either way and 8 panels");
      return;
    }
    s.cols = cols; s.rows = rows;
    chainPreset(false, false, false);
    settingsSave();
    restartBlank();
  }
  else if (!strcmp(cmd, "chain") && a1 && a2 && strlen(a1) == 2 && (a1[0] == 't' || a1[0] == 'b') &&
           (a1[1] == 'l' || a1[1] == 'r') && (!strcmp(a2, "z") || !strcmp(a2, "s"))) {
    chainPreset(a1[1] == 'r', a1[0] == 'b', a2[0] == 's');
    placementChanged();
  }
  else if (!strcmp(cmd, "panel") && a1 && a2 && a3 && a4) {
    long n = v - 1, c = strtol(a2, nullptr, 10), r = strtol(a3, nullptr, 10), t = strtol(a4, nullptr, 10);
    if (n < 0 || n >= panelCount() || c < 0 || c >= s.cols || r < 0 || r >= s.rows || t < 0 || t > 3) {
      Serial.println("Panel: <n 1..panels> <col> <row> <turn 0..3>");
      return;
    }
    s.panelCol[n] = c; s.panelRow[n] = r; s.panelRot[n] = t;
    placementChanged();
  }
  else if (!strcmp(cmd, "rot") && a1 && v >= 0 && v <= 3) {
    s.rotation = v;
    if (wall) { wall->setRotation(v); }
    placementChanged();
  }
  else if (!strcmp(cmd, "depth") && a1) { setAndRestart(s.depth, v, 2, 8); }
  else if (!strcmp(cmd, "clk") && a1) {
    if (v != 8 && v != 16 && v != 20) { Serial.println("Clock: 8, 16 or 20"); return; }
    setAndRestart(s.clkMHz, v, 8, 20);
  }
  else if (!strcmp(cmd, "rate") && a1) { setAndRestart(s.minRate, v, 30, 255); }
  else if (!strcmp(cmd, "phase") && a1) { setAndRestart(s.clkPhase, v, 0, 1); }
  else if (!strcmp(cmd, "chip") && a1) {
    for (uint8_t i = 0; i < CHIP_COUNT; i++) {
      if (!strcmp(a1, CHIP_NAMES[i])) { setAndRestart(s.chip, i, 0, CHIP_COUNT - 1); return; }
    }
    Serial.println("Chip: shift, fm6124, fm6126a, icn2038s, mbi5124 or dp3246");
  }
  else if (!strcmp(cmd, "double") && a1) { setAndRestart(s.doubleBuf, v, 0, 1); }
  else if (!strcmp(cmd, "blank") && a1) { setAndRestart(s.latBlank, v, 0, 4); }
  else if (!strcmp(cmd, "drive") && a1 && v >= 0 && v <= 3) {
    s.drive = v;
    settingsSave();
    if (panelOk) { setDrive(v); }
    Serial.printf("Drive strength %ld\n", v);
  }
  else if (!strcmp(cmd, "bright") && a1 && v >= 0 && v <= 255) { setBrightness(v); }
  else if (!strcmp(cmd, "screen") && a1 && v >= 1 && v <= SCR_COUNT) { showScreen(v - 1); }
  else if (!strcmp(cmd, "wifi")) { prefs.putBool("wifitest", true); restartBlank(); }
  else if (!strcmp(cmd, "i2c")) { scanI2c(); }
  else if (!strcmp(cmd, "defaults")) { settingsDefaults(); settingsSave(); restartBlank(); }
  else if (!strcmp(cmd, "restart")) { restartBlank(); }
  else { Serial.println("? - 'help' lists the commands"); }
}

void pollConsole() {
  static char line[96];
  static uint8_t len = 0;
  while (Serial.available()) {
    char c = Serial.read();
    if (c == '\r' || c == '\n') {
      if (len) { line[len] = 0; Serial.printf("> %s\n", line); runCommand(line); len = 0; }
    } else if (len < sizeof(line) - 1) {
      line[len++] = c;
    }
  }
}

// --- BOOT button ----------------------------------------------------------------
void pollButton() {
  static bool down = false, held = false;
  static unsigned long downAt = 0;
  bool now = digitalRead(PIN_BOOT) == LOW;
  if (now && !down) { down = true; held = false; downAt = millis(); }
  if (now && down && !held && millis() - downAt >= HOLD_MS) {
    held = true;
    uint8_t next = BRIGHT_STEPS[0];
    for (uint8_t b : BRIGHT_STEPS) { if (b > s.brightness) { next = b; break; } }
    setBrightness(next);
  }
  if (!now && down) {
    down = false;
    if (!held && millis() - downAt >= 30) { showScreen(screen + 1); }
  }
}

// --- Setup and loop -------------------------------------------------------------
void setup() {
  Serial.begin(115200);
  for (int i = 0; i < 30 && !Serial; i++) { delay(100); }   // give the USB console a moment
  pinMode(PIN_BOOT, INPUT_PULLUP);
  Serial.printf("\nWall clock spike. Reset reason: %s\n", resetReasonName(esp_reset_reason()));

  prefs.begin("wcspike");
  settingsLoad();
  uint8_t boots = prefs.getUChar("boots", 0);
  if (boots >= 3) {
    Serial.println("Three starts in a row did not get far: settings back to the defaults");
    settingsDefaults();
    settingsSave();
    boots = 0;
  }
  prefs.putUChar("boots", boots + 1);
  buildCells();
  screen = prefs.getUChar("screen", SCR_CHAIN) % SCR_COUNT;
  for (int v = 0; v < 256; v++) { gifGamma[v] = (uint8_t)lroundf(powf(v / 255.0f, 2.2f) * 255.0f); }

  Wire.begin(PIN_SDA_BOARD, PIN_SCL_BOARD, 100000);
  wireExt.begin(PIN_SDA_EXT, PIN_SCL_EXT, 100000);
  scanI2c();

  bool wifiTest = prefs.getBool("wifitest", false);
  if (wifiTest) { prefs.putBool("wifitest", false); }
  bool joined = wifiTest && wifiJoin();
  Probe before = { 0, 0, 0 };
  if (joined) { Serial.println("WiFi test: probing the router, panel not started yet ..."); before = probeRouter(); }

  panelOk = panelStart();
  if (panelOk) {
    wall = new Wall(s.cols * PANEL, s.rows * PANEL);
    wall->setRotation(s.rotation);
  }
  printStatus();
  Serial.println("'help' lists the commands.");

  if (joined && panelOk) {
    uint8_t shown = screen;
    screen = SCR_RAMPS;                  // a lit panel for the test
    drawScreen(true);
    Probe at[4];
    for (uint8_t d = 0; d < 4; d++) {
      setDrive(d);
      delay(500);
      Serial.printf("WiFi test: probing with the panel running at drive strength %u ...\n", d);
      at[d] = probeRouter();
    }
    setDrive(s.drive);
    Serial.printf("WiFi test, %u TCP connects to %s:%u each (brightness %u, ramps on the panel):\n",
                  PROBE_COUNT, WiFi.gatewayIP().toString().c_str(), PROBE_PORT, s.brightness);
    printProbe("panel not started", before);
    char label[32];
    for (uint8_t d = 0; d < 4; d++) {
      snprintf(label, sizeof(label), "panel on, drive %u", d);
      printProbe(label, at[d]);
    }
    screen = shown;
  }
  if (joined) { wifiOff(); }
  showScreen(screen);
}

void loop() {
  static unsigned long lastSecond = millis();
  static uint32_t lastEdges = frameEdges;
  static bool stable = false;

  pollConsole();
  pollButton();
  drawScreen(false);

  unsigned long now = millis();
  if (now - lastSecond >= 1000) {
    uint32_t edges = frameEdges;
    measuredHz = (edges - lastEdges) * 1000UL / (now - lastSecond);
    lastEdges = edges;
    lastSecond = now;
  }
  if (!stable && now >= STABLE_MS) {
    stable = true;
    prefs.putUChar("boots", 0);
  }
  delay(1);
}
