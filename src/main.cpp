// The home WiFi form (/wifi, POST). Returns what is wrong with it, or "" once
// the credentials in RAM have been replaced. A password left empty keeps the
// stored one.
String applyWifiForm(const String &body) {
  String ssid = getParam(body, "ssid");
  String pw   = getParam(body, "pw");
  if (ssid.length() == 0 || ssid.length() > 32) { return "The network name must be 1 to 32 characters long."; }
  if (pw.length() != 0 && (pw.length() < 8 || pw.length() > 63)) { return "The password must be 8 to 63 characters long."; }
  // The same network and password again keep what the clock knows about them.
  bool same = strcmp(wifiCreds.ssid, ssid.c_str()) == 0 && (pw.length() == 0 || strcmp(wifiCreds.pass, pw.c_str()) == 0);
  memset(wifiCreds.ssid, 0, sizeof(wifiCreds.ssid));
  strncpy(wifiCreds.ssid, ssid.c_str(), sizeof(wifiCreds.ssid) - 1);
  if (pw.length()) {
    memset(wifiCreds.pass, 0, sizeof(wifiCreds.pass));
    strncpy(wifiCreds.pass, pw.c_str(), sizeof(wifiCreds.pass) - 1);
  }
  if (!same) {
    wifiCreds.verified = 0;          // a new config until a sync has worked over it
    joinOutcome = JOIN_NOT_TRIED;   // whatever happened, happened with the network before
  }
  Console.print("WiFi: stored "); Console.println(wifiCreds.ssid);
  return "";
}



// "just now", "12 min ago" or "3 h ago", for a millis() stamp.
void printAgo(Print &c, unsigned long at) {
  unsigned long minutes = (millisNow - at) / 60000UL;
  if (minutes == 0)        { c.print("just now"); }
  else if (minutes < 120)  { c.print(minutes); c.print(" min ago"); }
  else                     { c.print(minutes / 60); c.print(" h ago"); }
}

