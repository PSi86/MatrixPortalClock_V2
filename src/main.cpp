// The running program's size in flash, from its image's headers; 0 when they
// cannot be read. ESP.getSketchSize() gives the same, but verifies the whole
// image for it, its SHA-256 over 1.5 MB: 121-138 ms on the S3 (2026-10-22),
// in one step of the web server, so /api/state held the loop that long
// (0.4 ms now).
uint32_t programSize() {
  const esp_partition_t *app = esp_ota_get_running_partition();
  if (!app) { return 0; }
  esp_partition_pos_t pos = { app->address, app->size };
  esp_image_metadata_t image = {};
  return esp_image_get_metadata(&pos, &image) == ESP_OK ? image.image_len : 0;
}

