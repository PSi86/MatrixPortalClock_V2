  stored &= saveFaceSettings();
  stored &= saveUiSettings();
  stored &= saveFaceKeys();
  applyNoticeKeysForm(body);
  stored &= saveNoticeKeys();
  if (!ntpSyncOn() && syncState != SYNC_IDLE) { setSyncState(SYNC_IDLE); }
