// Collects what a Print-based helper writes, for a JSON string.
class StringPrint : public Print {
 public:
  String text;
  size_t write(uint8_t b) override { text += (char)b; return 1; }
};

void sendWebApp(Print &c) {
  c.println("HTTP/1.1 200 OK");
  c.println("Content-Type: text/html; charset=utf-8");
  c.println("Content-Encoding: gzip");
  c.print("Content-Length: "); c.println(WEBUI_GZ_LEN);
  c.println("Cache-Control: no-cache");
  c.println("Connection: close");
  c.println();
  c.write(WEBUI_GZ, WEBUI_GZ_LEN);
}

void sendJson(Print &c, JsonDocument &doc, int code) {   // code: 200 unless given (clock_state.h)
  c.print("HTTP/1.1 "); c.print(code);
  c.println(code == 200 ? " OK" : code == 400 ? " Bad Request" : code == 404 ? " Not Found" :
            code == 413 ? " Content Too Large" : " Error");
  c.println("Content-Type: application/json");
  c.println("Cache-Control: no-store");
  c.println("Connection: close");
  c.println();
  serializeJson(doc, c);
}

// The answer to a change tried live: nothing when it asked for no preview,
