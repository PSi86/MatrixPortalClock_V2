// What moves: the panel's brightness and light, the time, the screen, and the
// info band's sources and items. Polled by the page.
void apiStatusInto(JsonDocument &d) {
  d["bright"] = effectiveBrightness;
  if (lastLux >= 0) { d["lux"] = serialized(String(lastLux, 1)); } else { d["lux"] = nullptr; }
#if BOARD_WAVESHARE_WALL
  if (roomValid) {   // the room's, filtered and corrected; absent without the sensor
    d["temp"] = serialized(String(roomTempNow(), 1));
    d["hum"] = lroundf(roomHumNow());
    d["tempSensor"] = serialized(String(roomTemp, 1));   // as the sensor reads, for its warmth
    d["humSensor"] = lroundf(roomHum);
  }
#endif
  d["clockSet"] = clockIsSet();
  if (clockIsSet()) {
    time_t local = clockNow() + tzTotalOffset();
    char hm[8];
    snprintf(hm, sizeof(hm), "%02d:%02d", clockHour(local), clockMinute(local));
    d["clock"] = hm;
  }
  d["src"] = timeSourceText();
  d["timeLine"] = timeStatusText();
  d["rot"] = matrix.getRotation();
  d["screen"] = (uint8_t)screen;
  d["gif"] = (screen == SCREEN_GIF);
  JsonArray feeds = d["feeds"].to<JsonArray>();
  for (uint8_t f = 0; f < FEED_COUNT; f++) {
    const FeedRun &r = feedRuns[f];
    JsonObject o = feeds.add<JsonObject>();
    o["on"] = feedOn(f);
    o["always"] = FEEDS[f].needsAlways;   // needs continuous network access
    // Why it does not fetch, if it does not: the page says so.
    if (!feedSettings.located)                       { o["blocked"] = "place"; }
    else if (!wifiStored())                          { o["blocked"] = "wifi"; }
    else if (FEEDS[f].needsAlways && !lanIsOn())     { o["blocked"] = "always"; }
    else if (!clockIsSet())                          { o["blocked"] = "time"; }
    o["failures"] = r.failures;
    if (r.error[0]) { o["error"] = r.error; }
    if (r.okAt) {
      char when[16];
      bandWhen(when, sizeof(when), r.okAt);
      o["okAt"] = when;
      o["ms"] = r.ms;
      if (r.bytes >= 0) { o["bytes"] = r.bytes; }
    }
  }
  d["place"] = feedPlace;
  // The minute of the next info round, in the clock's time; empty while it is off.
  char roundAt[16] = "";
  if (feedSettings.roundMinutes && clockIsSet()) {
    unsigned long in = roundMinuteAt ? 0 : roundNextIn();
    bandWhen(roundAt, sizeof(roundAt), clockNow() + (time_t)((in + 999UL) / 1000UL));
  }
  d["round"] = roundAt;
  JsonArray items = d["items"].to<JsonArray>();
  for (uint8_t i = 0; i < bandItemCount; i++) {
    JsonObject o = items.add<JsonObject>();
    char until[16];
    bandWhen(until, sizeof(until), bandItems[i].until);
    o["key"] = bandItems[i].key;
    o["text"] = bandItems[i].text;
    o["icon"] = bandItems[i].icon;
    o["alert"] = bandItems[i].level == LEVEL_ALERT;
    o["until"] = until;
    o["shows"] = itemShowsHere(bandItems[i]);
    o["ha"] = bandItems[i].feed == SOURCE_HA;
  }
  haStatusInto(d["haStatus"].to<JsonObject>());
}


